"""Schemas for evaluation test cases and results."""

import json
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class TestCase:
    """Represents a single test case for evaluation.

    Attributes:
        question: The input question/task
        agent_output: The output generated by the agent
        tool_calls: List of tools called by the agent
        expected_tool_calls: Dictionary containing 'complete' and 'accepted' sequences
        category: Category of the test (e.g., 'Tool', 'Workflow')
        test_name: Name of the specific test
        session: Session identifier
        question_variation: Variation number of the question (0-10)
        note: Additional notes or context for evaluation
        trace_id: Optional Langfuse trace ID
        repeated_tool_calls: Whether there are repeated tool calls
        tool_call_correctness: Pre-computed correctness ('complete', 'partial', 'incorrect')
        metadata: Additional metadata
    """

    question: str
    agent_output: str
    tool_calls: List[str]
    expected_tool_calls: Dict[str, List[List[str]]]
    category: str
    test_name: str
    session: str
    question_variation: Optional[int] = None
    note: Optional[str] = None
    trace_id: Optional[str] = None
    repeated_tool_calls: bool = False
    tool_call_correctness: Optional[str] = None
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class EvaluationResult:
    """Represents the evaluation result for a test case.

    Attributes:
        test_case: The original test case
        scores: Dictionary of metric scores (None indicates missing/unavailable score)
        reasoning: Judge's reasoning for the scores
        raw_output: Raw output from the judge/evaluator
        metadata: Additional metadata about the evaluation
    """

    test_case: TestCase
    scores: Dict[str, Optional[float]]
    reasoning: str = ""
    raw_output: Any = None
    metadata: Dict[str, Any] = field(default_factory=dict)

    def get_score(self, metric: str, default: float = 0.0) -> Optional[float]:
        """Get a specific metric score.

        Args:
            metric: Name of the metric
            default: Default value if metric not found

        Returns:
            The score for the metric, or None if score is None
        """
        score = self.scores.get(metric, default)
        return score if score is not None else None

    def get_all_scores(self) -> Dict[str, Optional[float]]:
        """Get all scores.

        Returns:
            Dictionary of all metric scores
        """
        return self.scores.copy()


@dataclass
class BatchEvaluationResult:
    """Represents results for a batch of evaluations.

    Attributes:
        results: List of individual evaluation results
        aggregate_scores: Aggregated scores across all results
        metadata: Additional metadata about the batch evaluation
    """

    results: List[EvaluationResult]
    aggregate_scores: Dict[str, float] = field(default_factory=dict)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def get_results_by_category(self, category: str) -> List[EvaluationResult]:
        """Filter results by category.

        Args:
            category: Category name to filter by

        Returns:
            List of results matching the category
        """
        return [r for r in self.results if r.test_case.category == category]

    def get_average_score(self, metric: str) -> float:
        """Calculate average score for a metric across all results.

        Args:
            metric: Name of the metric

        Returns:
            Average score (excluding None values)
        """
        # Filter out None values and -1.0 (NOT APPLICABLE) values
        valid_scores: list[float] = []
        for r in self.results:
            if metric in r.scores and r.scores[metric] is not None:
                score = r.scores[metric]
                if score is not None and score != -1.0:  # Exclude NOT APPLICABLE
                    valid_scores.append(score)
        return sum(valid_scores) / len(valid_scores) if valid_scores else 0.0


def save_results_to_json(results: List[EvaluationResult], filename: str) -> None:
    """Serialize evaluation results to a JSON file."""
    new_results = []
    for result in results:
        if isinstance(result.test_case, TestCase):
            test_case_dict = result.test_case.__dict__
        else:
            test_case_dict = str(result.test_case)

        entry: Dict[str, Any] = {
            "test_case": test_case_dict,
            "scores": result.scores,
        }
        if result.reasoning:
            entry["reasoning"] = result.reasoning
        new_results.append(entry)

    with open(filename, "w") as f:
        json.dump(new_results, f, indent=4)


def load_results_from_json(filename: str) -> List[EvaluationResult]:
    """Deserialize evaluation results from a JSON file."""
    with open(filename, "r") as f:
        data = json.load(f)

    new_data = []
    for item in data:
        for key, value in item.items():
            if key == "test_case" and isinstance(value, dict):
                item[key] = TestCase(**value)

        new_data.append(EvaluationResult(
            test_case=item["test_case"],
            scores=item["scores"],
            reasoning=item.get("reasoning", ""),
        ))
    return new_data
